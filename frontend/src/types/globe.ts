export type MartianFeatureCategory =
  | 'MONS'      // Volcanoes and Mountains
  | 'CRATER'    // Impact Craters and Giant Basins
  | 'VALLIS'    // Canyons, Chasmata and Outflow Valleys
  | 'PLANITIA'  // Lowland Plains
  | 'PLANUM'    // High Plateaus & Polar Ice Caps
  | 'LANDING';  // Historic In-situ Landing Sites

export interface UsgsMartianLandmark {
  id: string;
  name: string;
  latinName?: string;
  category: MartianFeatureCategory;
  categoryLabel: string;
  center: [number, number]; // [Latitude °N (-90 to +90), East Longitude °E (0 to 360)]
  diameter_km?: number;
  length_km?: number;
  area_km2?: number;
  elevation_m?: number;
  usgsQuadrangle: string; // IAU / USGS 1:5,000,000 Quadrangle
  description: string;
  scientificContext: string;
  color: string;
  sectorId?: string; // Links to high-res 3D reconstruction sector if available
}

export interface MarsRegion {
  id: string;
  name: string;
  featureType: string;
  center: [number, number]; // [lat, lon] in degrees
  bounds: {
    min_lat: number;
    max_lat: number;
    min_lon: number;
    max_lon: number;
  };
  area_km2: number;
  description: string;
  missionContext: string;
  color: string;
  usgsQuadrangle?: string;
  landmarkRefId?: string;
}

